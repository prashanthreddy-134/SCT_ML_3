IMG_SIZE = (64, 64)
CLASS_NAMES = ["cat", "dog"]
IMAGE_EXTS = {".jpg", ".jpeg", ".png", ".bmp"}
MAX_PER_CLASS = 1000

def extract_features(path):
    img = Image.open(path).convert("L").resize(IMG_SIZE)
    return hog(np.asarray(img), orientations=9, pixels_per_cell=(8, 8), cells_per_block=(2, 2))

def label_from_parts(parts):
    for part in parts:
        p = part.lower()
        if p.startswith("cat"): return 0
        if p.startswith("dog"): return 1
    return None

